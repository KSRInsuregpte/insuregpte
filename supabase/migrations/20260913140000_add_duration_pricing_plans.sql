-- Server-authoritative access plans for paid subject practice.
-- Prices are stored in Supabase; browser values are never accepted.

CREATE TABLE IF NOT EXISTS public.subject_pricing_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    duration_days integer NOT NULL,
    price numeric(10,2) NOT NULL,
    currency_code text NOT NULL DEFAULT 'INR',
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT subject_pricing_plans_duration_check
        CHECK (duration_days IN (15, 30, 60, 90)),
    CONSTRAINT subject_pricing_plans_price_check CHECK (price >= 0),
    CONSTRAINT subject_pricing_plans_duration_unique UNIQUE (duration_days)
);

