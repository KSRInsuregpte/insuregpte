COMMENT ON FUNCTION public.add_subject_to_cart(bigint, integer) IS
    'Adds or replaces one subject cart item using the server-side pricing plan.';
COMMENT ON FUNCTION public.get_my_cart_with_plans() IS
    'Returns the authenticated cart with server-recorded duration and price.';

